/** 영상 길이에 비례한 목표 분량 (공백 포함 글자 수) */
function lengthInstruction(video, length) {
  const minutes = Math.max(1, (video.lengthSeconds || 600) / 60);
  const round = (n) => Math.round(n / 500) * 500;
  if (length === "brief") {
    const target = round(Math.min(5000, Math.max(1500, minutes * 200)));
    return `분량: 핵심 위주로 공백 포함 약 ${target.toLocaleString()}자. 영상의 주요 주제는 모두 다루되, 세부 예시는 가장 중요한 것만 남깁니다.`;
  }
  const target = round(Math.min(16000, Math.max(3000, minutes * 450)));
  return `분량: 공백 포함 약 ${target.toLocaleString()}자 이상 (영상 정보가 많으면 더 길어도 됩니다). 요약하지 말고 영상의 모든 내용을 자세히 풀어 쓰세요. 다만 영상에 정보가 적으면 억지로 늘리지 않습니다.`;
}

// 영상 장면 이미지를 넣을 때만 추가하는 지침
function sceneInstructions(video) {
  const limit = video.lengthSeconds ? ` 영상 길이(${formatTime(video.lengthSeconds)})를 넘지 않게 합니다.` : "";
  return [
    "영상 장면 이미지: 본문 중 이미지가 있으면 이해가 쉬워지는 지점 3~6곳에 영상 장면 캡처를 넣습니다.",
    "- 형식: 이미지로 보여 줄 문단 바로 다음, 앞뒤를 빈 줄로 띄운 단독 줄에 [[장면 시작-끝 | 캡션]] (예: [[장면 3:10-3:40 | 수면 단계별 뇌파 그래프]])",
    `- 시작-끝은 자막의 [분:초] 표시를 보고, 바로 위 문단의 내용을 화자가 실제로 말하는 구간으로 좁게(15~60초) 적습니다. 그 문단의 핵심 단어가 자막에 처음 나오는 시각을 시작으로 잡습니다. 그 구간의 장면 여러 장 중 내용에 가장 잘 맞는 장면을 나중에 골라 넣습니다.${limit}`,
    "- 슬라이드, 도표, 시연, 화면 속 글자, 실제 물건·장소처럼 눈으로 보여줄 것이 있을 법한 구간을 우선 고릅니다.",
    "- 캡션은 바로 위 문단의 핵심 단어(개념·물건·고유명사 등)를 넣어, 그 장면에 보일 법한 것을 25자 이내로 씁니다.",
    "- 도입부 바로 아래에 대표 장면 1개를 넣을 수 있고, 나머지는 서로 다른 소제목 구간에 고르게 배치합니다. 핵심 정리와 출처 부분에는 넣지 않습니다.",
    "- 이 표시는 이미지로 바뀌므로, 본문에서 '아래 장면처럼' 같은 말로 이미지를 가리키지 않습니다.",
    "- 이 [[장면 ...]] 표시만은 '타임스탬프를 본문에 넣지 않는다'는 규칙의 예외입니다. 그 밖의 본문에는 여전히 타임스탬프를 넣지 않습니다.",
  ].join("\n");
}

/**
 * @param {object} video
 * @param {string} transcript
 * @param {string} tone
 * @param {{ scenes?: boolean, length?: "detailed" | "brief" }} [options]
 *   scenes: 영상 장면 캡처 위치 표시를 넣을지 / length: 분량 (자세히 | 핵심만)
 */
export function buildUserMessage(video, transcript, tone, { scenes = false, length = "detailed" } = {}) {
  const lines = [
    "아래 유튜브 영상을 바탕으로 블로그 게시글을 작성해 주세요.",
    "",
    "<video_info>",
    `제목: ${video.title}`,
    `채널: ${video.channel}`,
    video.lengthSeconds ? `길이: ${formatTime(video.lengthSeconds)}` : null,
    `URL: ${video.url}`,
    `자막: ${video.transcriptLanguage}${video.transcriptAuto ? " (자동 생성 — 오인식이 있을 수 있음)" : ""}`,
    "</video_info>",
    "",
  ];
  if (video.description?.trim()) {
    lines.push("<video_description>", video.description.trim(), "</video_description>", "");
  }
  lines.push(
    "<transcript>",
    transcript,
    "</transcript>",
    "",
    `문체: ${TONES[tone] ?? TONES.friendly}`,
    lengthInstruction(video, length),
  );
  if (scenes) lines.push("", sceneInstructions(video));
  return lines.filter((l) => l !== null).join("\n");
}

